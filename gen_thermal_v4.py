# ── Cell 4: Stress polynomial (train cells only) ───────────────────────────────
cells.append(md(
    "## 4 · Fit Stress Function (Training Cells Only)\n\n"
    "We fit an empirical polynomial:\n\n"
    "```\n"
    "fade_rate = a0 + a1*T + a2*T^2 + a3*I\n"
    "```\n\n"
    "from training cells only (no leakage). Then calibrate K so that:\n\n"
    "```\n"
    "stress(T, I) = K * (T - 35)^2 * |I|\n"
    "```\n\n"
    "approximates the data-derived fade rate. K is chosen so that the stress term\n"
    "produces physically meaningful reward magnitude (~0.1-10 per step).\n\n"
    "> **Note:** This is an *empirically calibrated* stress function, not a direct\n"
    "> physical law. The 35°C threshold is consistent with Waldmann et al. (2014)\n"
    "> for Li-ion cells, but the exact coefficients are data-derived from Severson cells.\n"
))
cells.append(code([
    "# Extract per-cycle (T_mean, I_mean, fade_rate) from TRAINING CELLS ONLY\n",
    "records = []\n",
    "for key in train_keys:\n",
    "    cell = bat_dict[key]\n",
    "    summ = cell['summary']\n",
    "    Q = np.array(summ.get('QD', summ.get('Qd', [])))\n",
    "    Tavg = np.array(summ.get('Tavg', summ.get('T_avg', [])))\n",
    "    cycs = np.arange(len(Q))\n",
    "    if len(Q) < 20: continue\n",
    "    # fade rate = -dQ/dcycle (positive when capacity decreasing)\n",
    "    fade = -np.gradient(Q, cycs)\n",
    "    # typical discharge C-rate from cycle data\n",
    "    I_dis = np.ones_like(Q) * 4.0  # LFP cells cycled at ~4C discharge\n",
    "    for i in range(10, len(Q)-5):\n",
    "        if not np.isnan(Tavg[i]) and Tavg[i] > 20:\n",
    "            records.append({'T': Tavg[i], 'I': I_dis[i], 'fade': float(fade[i])})\n",
    "\n",
    "T_arr = np.array([r['T'] for r in records])\n",
    "I_arr = np.array([r['I'] for r in records])\n",
    "f_arr = np.array([r['fade'] for r in records])\n",
    "\n",
    "# Filter outliers\n",
    "mask = (np.abs(f_arr) < np.percentile(np.abs(f_arr), 98))\n",
    "T_arr, I_arr, f_arr = T_arr[mask], I_arr[mask], f_arr[mask]\n",
    "\n",
    "# Polynomial fit: fade = a0 + a1*T + a2*T^2 + a3*I\n",
    "A = np.column_stack([np.ones(len(T_arr)), T_arr, T_arr**2, I_arr])\n",
    "coeffs, res, _, _ = np.linalg.lstsq(A, f_arr, rcond=None)\n",
    "f_pred = A @ coeffs\n",
    "ss_res = np.sum((f_arr - f_pred)**2)\n",
    "ss_tot = np.sum((f_arr - f_arr.mean())**2)\n",
    "r2_poly = 1 - ss_res/ss_tot if ss_tot > 0 else 0\n",
    "a0, a1, a2, a3 = coeffs\n",
    "\n",
    "print(f'Stress polynomial fit on {len(T_arr):,} cycles from {len(train_keys)} training cells')\n",
    "print(f'  fade = {a0:.6f} + {a1:.6f}*T + {a2:.6f}*T^2 + {a3:.6f}*I')\n",
    "print(f'  Polynomial R² = {r2_poly:.4f}')\n",
    "print(f'  T range: {T_arr.min():.1f}–{T_arr.max():.1f}°C | I range: {I_arr.min():.1f}–{I_arr.max():.1f} A')\n",
    "\n",
    "# Calibrate K_STRESS via cycle-integrated OLS on stress-active training cycles.\n",
    "# For each cycle where T > T_ONSET at any timestep:\n",
    "#   S0_cycle = sum_t max(0, T_t - T_ONSET)^2 * |I_t| * dt   (unnormalised)\n",
    "#   fade(n)  = Q_d(n-1) - Q_d(n)                             (Ah/cycle)\n",
    "# OLS: K = sum(fade * S0) / sum(S0^2)\n",
    "T_ONSET_CAL = 35.0\n",
    "OLS_NUM, OLS_DEN = 0.0, 0.0\n",
    "for _key in train_keys:\n",
    "    _cell = bat_dict[_key]\n",
    "    _Qd = np.array(_cell['summary']['QDischarge'], dtype=float)\n",
    "    for _cs, _cd in _cell['cycles'].items():\n",
    "        _cn = int(_cs)\n",
    "        if _cn < 10 or _cn >= len(_Qd): continue\n",
    "        _fade = float(_Qd[_cn-1] - _Qd[_cn])\n",
    "        _Tc = np.array(_cd.get('T',''), dtype=float)\n",
    "        _Ic = np.abs(np.array(_cd.get('I',''), dtype=float))\n",
    "        if len(_Tc) < 4 or len(_Ic) < 4: continue\n",
    "        _n = min(len(_Tc), len(_Ic)); _Tc, _Ic = _Tc[:_n], _Ic[:_n]\n",
    "        _dt = 1.0 / max(len(_Tc), 1)\n",
    "        _S0 = float(np.sum(np.maximum(0, _Tc - T_ONSET_CAL)**2 * _Ic) * _dt)\n",
    "        if _S0 > 0:\n",
    "            OLS_NUM += _fade * _S0\n",
    "            OLS_DEN += _S0 * _S0\n",
    "K_STRESS = float(OLS_NUM / (OLS_DEN + 1e-12))\n",
    "if K_STRESS < 1e-8:\n",
    "    print(f'WARNING: K_STRESS OLS gave {K_STRESS:.2e}; falling back to mean-ratio calibration')\n",
    "    T_op = np.clip(T_arr - T_ONSET_CAL, 0, None)\n",
    "    K_STRESS = float(np.mean(np.abs(f_arr)) / (np.mean((T_op**2)*np.abs(I_arr)) + 1e-10))\n",
    "print(f'  K_STRESS (OLS cycle-integrated) = {K_STRESS:.6e}')\n",
    "\n",
    "def stress_fn(T, I):\n",
    "    \"\"\"Physical thermal stress: OLS-calibrated on Severson training cells.\"\"\"\n",
    "    excess = max(0.0, T - T_ONSET_CAL)\n",
    "    return float(K_STRESS * excess**2 * abs(I))\n",
]))

